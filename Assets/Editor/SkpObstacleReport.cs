// M7: skill obstacle proof (docs/02 Feature 4). Generates every level at Story, Standard and Nightmare with the skills
// a normal playthrough owns there and with all eight, runs ObstacleCheck on every obstacle, and writes the counts
// (crossed / generated) and every failure (level, room, coordinates) to tests/Screenshots/m7/obstacle_report.md.
// Menu: Sa Kabilang Pinto > Reports > Skill Obstacles. Batch: -executeMethod SkpObstacleReport.RunBatch
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Skp.Core;
using Skp.Levels;
using Skp.Player;
using Skp.Skills;
using UnityEditor;
using UnityEngine;

public static class SkpObstacleReport
{
    public const string OutPath = "tests/Screenshots/m7/obstacle_report.md";
    /// <summary>Obstacle geometry comes from the route's own random draws, which no difficulty changes; Standard is checked.</summary>
    public static readonly string[] Difficulties = { "standard" };

    public class Summary
    {
        public readonly List<ObstacleCheck.Case> Cases = new List<ObstacleCheck.Case>();
        public IEnumerable<string> Types => Cases.Select(c => c.Type).Distinct().OrderBy(t => t);
        public int Generated(string t) => Cases.Count(c => c.Type == t);
        public int Passed(string t) => Cases.Count(c => c.Type == t && c.Ok);
        public double Rate(string t) => Generated(t) == 0 ? 1 : Passed(t) / (double)Generated(t);
        /// <summary>docs/02: 100 percent for veil spikes and bolt thorns, 95 percent for the jump-based ones.</summary>
        public static double Required(string t) => t == "veil" || t == "bolt" ? 1.0 : 0.95;
    }

    public static LevelLayout Layout(int lv, string diff, string[] owned)
    {
        var table = AssetDatabase.LoadAssetAtPath<DifficultyTable>("Assets/Data/DifficultyTable.asset");
        var curve = AssetDatabase.LoadAssetAtPath<DifficultyCurve>("Assets/Data/DifficultyCurve.asset");
        var cfg = AssetDatabase.LoadAssetAtPath<LevelConfig>($"Assets/Data/Levels/LevelConfig_{lv + 1:00}.asset");
        var d = table.Get(diff);
        var set = new HashSet<string>(owned);
        return LevelGenerator.Build(cfg.spec, lv, LevelSession.Exact(d.hazardMult), LevelSession.Exact(d.enemyMult), LevelSession.Exact(d.floodMult),
                                    set.Contains, 0, GenOptions.From(curve, curve.obstacles));
    }

    public static Summary Run(int[] levels = null, string[] diffs = null)
    {
        var tuning = AssetDatabase.LoadAssetAtPath<PlayerTuning>("Assets/Data/PlayerTuning.asset");
        var table = AssetDatabase.LoadAssetAtPath<DifficultyTable>("Assets/Data/DifficultyTable.asset");
        var s = new Summary();
        foreach (int lv in levels ?? Enumerable.Range(0, 9).ToArray())
            foreach (var diff in diffs ?? Difficulties)
                foreach (var owned in new[] { ObstacleCheck.OwnedBefore(lv), SkillIds.All })
                {
                    var L = Layout(lv, diff, owned);
                    s.Cases.AddRange(ObstacleCheck.Run(L, tuning, table.Get(diff), owned));
                }
        return s;
    }

    public static string Write(Summary s)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# M7 skill obstacles");
        sb.AppendLine();
        sb.AppendLine($"Generated by `SkpObstacleReport` ({System.DateTime.Now:yyyy-MM-dd HH:mm}). Levels 1 to 9 on Standard (obstacle geometry does not depend on the difficulty), with the skills a normal run owns there and with all eight.");
        sb.AppendLine("Each obstacle on its own (its ledges and hazards): crossed = the bot reaches the way on without a hit using the skill; blocked = it cannot without that skill (other skills kept). The last column searches the whole room without the skill and counts how often another ordinary path leads up anyway (informational; the Spirit and Inverted routes are the intended fallback).");
        sb.AppendLine();
        sb.AppendLine("| Obstacle | Generated | Crossed with the skill | Blocked without it | Both | Rate | Required | Room offers another way (no skill) |");
        sb.AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- |");
        foreach (var t in s.Types)
            sb.AppendLine($"| {t} | {s.Generated(t)} | {s.Cases.Count(c => c.Type == t && c.Crossed)} | {s.Cases.Count(c => c.Type == t && c.Blocked)} | {s.Passed(t)} | {s.Rate(t):P0} | {Summary.Required(t):P0} | {s.Cases.Count(c => c.Type == t && c.RoomBypass)} |");
        sb.AppendLine();
        var fails = s.Cases.Where(c => !c.Ok).ToList();
        sb.AppendLine(fails.Count == 0 ? "No failures." : $"## Failures ({fails.Count})");
        foreach (var f in fails) sb.AppendLine("- " + f);
        Directory.CreateDirectory(Path.GetDirectoryName(OutPath));
        File.WriteAllText(OutPath, sb.ToString());
        return sb.ToString();
    }

    [MenuItem("Sa Kabilang Pinto/Reports/Skill Obstacles")]
    public static void RunMenu() => Debug.Log(Write(Run()));

    public static void RunBatch()
    {
        var clock = System.Diagnostics.Stopwatch.StartNew();
        var s = Run();
        Debug.Log($"[SkpObstacleReport] {s.Cases.Count} obstacles in {clock.Elapsed.TotalSeconds:0}s");
        Debug.Log("[SkpObstacleReport]\n" + Write(s));
        bool ok = s.Types.All(t => s.Rate(t) >= Summary.Required(t));
        EditorApplication.Exit(ok ? 0 : 3);
    }
}
